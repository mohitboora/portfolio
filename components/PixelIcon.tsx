const ICONS = {
  user: ["..####..", ".######.", ".######.", "..####..", "...##...", ".######.", "########", "########"],
  book: [".######.", "#++#+++#", "#++#+++#", "#++#+++#", "#++#+++#", "#++#+++#", ".######.", "........"],
  case: ["..####..", "..#..#..", "########", "#++++++#", "########", "#++##++#", "#++++++#", "########"],
  sword: ["......##", ".....###", "....###.", "#..###..", ".####...", "..##....", ".#.#....", "#......."],
  globe: ["..####..", ".#.##.#.", "#..##..#", "########", "#..##..#", ".#.##.#.", "..####..", "........"],
  github: ["#......#", "##....##", "########", "#.####.#", "########", "########", ".######.", "..####.."],
  linkedin: ["##......", "........", "##.####.", "##.#..#.", "##.#..#.", "##.#..#.", "##.#..#.", "........"],
  instagram: ["########", "#......#", "#.####.#", "#.#..#.#", "#.#..#.#", "#.####.#", "#......#", "########"],
  mail: ["########", "##....##", "#.#..#.#", "#..##..#", "#......#", "#......#", "########", "........"],
  phone: [".####...", ".#..#...", ".#..#...", ".#..#...", ".#..#...", ".#..#...", ".####...", "..##...."],
  chevron: ["#......#", ".#....#.", "..#..#..", "...##...", "........", "........", "........", "........"],
} as const;

export type IconName = keyof typeof ICONS;

export default function PixelIcon({ name, size = 24, className = "" }: { name: IconName; size?: number; className?: string }) {
  const rows = ICONS[name];
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 8 8"
      shapeRendering="crispEdges"
      className={className}
      fill="currentColor"
      aria-hidden="true"
      style={{ filter: "drop-shadow(0 0 5px rgba(122,245,154,0.55))" }}
    >
      {rows.flatMap((row, y) =>
        row.split("").map((ch, x) =>
          ch === "#" || ch === "+" ? <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} opacity={ch === "+" ? 0.4 : 1} /> : null,
        ),
      )}
    </svg>
  );
}
